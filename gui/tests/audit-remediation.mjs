// Interaction and ACL configuration regression. The browser does not validate native dispatch.
import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { mockDesktop } from './ipc-fixture.mjs';

const nativeFile = filename => readFile(new URL(`../src-tauri/${filename}`, import.meta.url), 'utf8');
const build = await nativeFile('build.rs');
const handler = (await nativeFile('src/main.rs')).match(/\.invoke_handler\(tauri::generate_handler!\[([^\]]+)\]/)[1];
const commands = handler.trim().replace(/\s/g, '').split(',').map(c => c.split('::').at(-1));
assert.deepEqual([...build.matchAll(/^    "(\w+)",$/gm)].map(m => m[1]).sort(), commands.toSorted());
assert.match(build, /\.app_manifest\(tauri_build::AppManifest::new\(\).commands\(COMMANDS\)\)/);
const main = JSON.parse(await nativeFile('capabilities/main.json'));
const log = JSON.parse(await nativeFile('capabilities/log.json'));
assert.deepEqual(main.windows, ['main']);
assert.deepEqual(log.windows, ['log']);
assert.deepEqual(log.permissions.sort(), ['allow-clear-log', 'allow-get-log', 'allow-set-log-open', 'core:event:allow-listen', 'core:event:allow-unlisten']);
const mainCustom = main.permissions.filter(p => p.startsWith('allow-')).sort();
assert.deepEqual(mainCustom, commands.filter(c => !['get_log', 'clear_log'].includes(c)).map(c => `allow-${c.replaceAll('_', '-')}`).sort());

const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH });
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 800 } });
  page.setDefaultTimeout(8000);
  await mockDesktop(page);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const panel = name => page.getByRole('tabpanel', { name, exact: true });
  const tool = (name) => page.getByRole('toolbar', { name: 'Workspace tools' }).getByRole('button', { name, exact: true });
  const button = (name) => page.getByRole('button', { name, exact: true });
  const calls = command => page.evaluate(cmd => window.exorCalls.filter(([name]) => name === cmd).map(([, args]) => args), command);
  await page.goto('https://exor.test/?desktop-slices');
  await tool('Settings').click();
  await button('Measure profile storage').click();
  await page.getByText('Held file bytes', { exact: true }).waitFor();
  await button('Browse destination…').click();
  const destination = page.getByLabel('Destination parent');
  assert.equal(await destination.inputValue(), String.raw`C:\Fixture`);
  await button('Create verified backup').click();
  const status = page.getByRole('region', { name: 'Profile storage and backup' }).getByRole('status');
  await status.getByText(/Verified 4 file/).waitFor();
  const archive = await page.getByLabel('Existing backup directory').inputValue();
  await button('Restore to separate copy').click();
  await status.getByText(/The active profile was not changed/).waitFor();
  assert.deepEqual(await calls('restore_profile_copy'), [{ backupPath: archive, destination: String.raw`C:\Fixture` }]);

  await tool('Cleanup summary').click();
  const cleanup = panel('Cleanup summary');
  await cleanup.getByLabel('Installation', { exact: true }).selectOption('9');
  await cleanup.getByLabel('Registered application').selectOption(String.raw`HKLM\Zed`);
  await button('Find application folders').click();
  const folders = cleanup.getByRole('group', { name: 'Approved folders' });
  const eligible = folders.getByRole('checkbox', { name: /This was the install folder/ });
  const outside = folders.getByRole('checkbox', { name: /Other-volume/ });
  assert(await outside.isDisabled());
  await eligible.check();
  const reviewButton = button('Review cleanup plan…');
  assert(await reviewButton.isDisabled(), 'a name suggestion is not cleanup authorization');
  await cleanup.getByRole('checkbox', { name: /Link this recorded session/ }).check();
  await page.evaluate(() => { window.deferPlan = true; });
  await reviewButton.click();
  await page.waitForFunction(() => !!window.releasePlan);
  await button('Stop preparing plan').click();
  await page.evaluate(() => window.releasePlan());
  await cleanup.getByRole('alert').getByText('Cleanup preparation cancelled.', { exact: false }).waitFor();
  assert.equal((await calls('apply_cleanup')).length, 0);
  assert.equal((await calls('link_cleanup_session')).length, 1);

  const review = cleanup.getByRole('region', { name: 'Review exact cleanup plan' });
  const confirm = review.getByRole('button', { name: 'Confirm: move reviewed files' });
  const approval = review.getByRole('checkbox', { name: /I approve moving exactly these 42 files/ });
  const prepare = async () => {
    await reviewButton.click();
    await review.getByText(/1 of 2 included-file pages opened/).waitFor();
    assert(await approval.isDisabled());
    assert(await confirm.isDisabled());
    await review.getByRole('button', { name: 'Exclusions', exact: true }).click();
    await review.getByText('System evidence is advisory.').waitFor();
    assert(await confirm.isDisabled());
    await review.getByRole('button', { name: 'Included files', exact: true }).click();
    await review.getByRole('button', { name: 'Next paths' }).click();
    await review.getByText(/Exact-42\.bin/).waitFor();
    await approval.check();
  };
  await prepare();
  await button('Cancel review').click();
  await review.waitFor({ state: 'hidden' });
  assert.equal((await calls('discard_cleanup_plan')).length, 1);
  assert.equal((await calls('apply_cleanup')).length, 0);

  await prepare();
  await page.evaluate(() => { window.failPlan = true; });
  await confirm.click();
  await review.getByRole('alert').getByText(/reviewed file changed/).waitFor();
  assert(await confirm.isDisabled());
  await button('Cancel review').click();
  await prepare();
  await confirm.click();
  await cleanup.getByRole('status').getByText('Moved 42 files to quarantine.').waitFor();
  const applied = await calls('apply_cleanup');
  assert.equal(applied.length, 2);
  assert.notEqual(applied[0].id, applied[1].id);
  assert(applied.every(a => a.approvedFiles === 42 && Object.keys(a).length === 2));

  const held = cleanup.getByRole('row').filter({ hasText: 'fixture-held' });
  await held.getByRole('button', { name: 'Rotate verified archive…' }).click();
  const rotation = page.getByRole('dialog', { name: 'Rotate a verified archive' });
  const rotate = rotation.getByRole('button', { name: 'Verify archive and rotate' });
  assert(await rotate.isDisabled());
  await rotation.getByLabel('Verified backup folder').fill(String.raw`C:\Fixture\other`);
  await rotate.click();
  await cleanup.getByRole('alert').getByText(/archive did not verify/).waitFor();
  await held.getByRole('cell', { name: 'In quarantine', exact: true }).waitFor();
  await held.getByRole('button', { name: 'Rotate verified archive…' }).click();
  await rotation.getByLabel('Verified backup folder').fill(archive);
  await rotate.click();
  await held.getByRole('cell', { name: 'Deleted locally', exact: true }).waitFor();
  assert.equal((await calls('purge_quarantine')).length, 0);

  await tool('Change inspector').click();
  const history = panel('Change inspector');
  await history.getByLabel('Installation', { exact: true }).selectOption('40');
  await history.getByLabel('From date (UTC)', { exact: true }).fill('2026-11-18');
  await history.getByLabel('Before date (UTC, exclusive)').fill('2026-11-19');
  await history.getByLabel('Change type').selectOption('modified');
  await history.getByText('Export matching changes', { exact: true }).click();
  await page.evaluate(() => { window.smallExport = true; });
  await button('Save changes JSON').click();
  await button('Save next older JSON part').click();
  const exports = await calls('save_changes');
  const filters = { filter: null, sessionId: 40, changeKind: 'modified', beforeId: null, fromDate: '2026-11-18', beforeDate: '2026-11-19' };
  assert.deepEqual(exports, [{ filters }, { filters: { ...filters, beforeId: 41 } }]);
  await page.evaluate(() => window.emitExor('shutdown-wait', 'Closing after the active operation reaches a safe stopping point.'));
  await page.getByRole('status').getByText(/Closing after the active operation/).waitFor();
  assert.deepEqual(errors, []);
  console.log('Audit remediation smoke passed: scoped review and cancellation, page approval and replay syntax, verified copy and rotation UX, UTC export continuation, close notice and split capabilities.');
} finally {
  await browser.close();
}
